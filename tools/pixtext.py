def text_width(s, scale=1):
    return len(s) * 4 * scale - scale


def draw_text(d, x, y, s, fill, scale=1):
    """d: PIL ImageDraw. Draws s with its top-left at (x, y)."""
    for ch in s:
        g = GLYPHS.get(ch.upper(), GLYPHS[' '])
        for j, row in enumerate(g):
            for i, v in enumerate(row):
                if v == '1':
                    d.rectangle((x + i * scale, y + j * scale, x + i * scale + scale - 1, y + j * scale + scale - 1), fill=fill)
        x += 4 * scale
